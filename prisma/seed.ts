  // Surface Types
  for (const name of surfaceTypes) {
    await prisma.surfaceType.upsert({
      where: { id: surfaceTypes.indexOf(name) + 1 },
      update: { name },
      create: { name },
    });
  }
  console.log(`✅ ${surfaceTypes.length} surface types`);

  // Provinces — upsert by name_th (unique) rather than by array position, so
  // re-ordering or removing an entry here never overwrites the wrong row.
  for (const p of provinces) {
    await prisma.province.upsert({
      where: { name_th: p.name_th },
      update: p,
      create: p,
    });
  }
  console.log(`✅ ${provinces.length} provinces`);

  // Districts — every province gets its full amphoe list. Safe to rebuild
